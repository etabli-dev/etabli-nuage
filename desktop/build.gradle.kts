/**
 * Generates Kotlin constants from the suite design file (design/coder-design-system.json),
 * so desktop colours, spacing, radii and type scale cannot drift from the shared tokens.
 */
abstract class GenerateDesktopSources : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val tokens: RegularFileProperty

    @get:Input
    abstract val appVersion: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        @Suppress("UNCHECKED_CAST")
        fun Any?.obj(key: String): Map<String, Any?> =
            (this as Map<String, Any?>)[key] as? Map<String, Any?> ?: error("Design file lacks '$key'")
        fun color(value: Any?): String {
            val hex = (if (value is Map<*, *>) value["value"] else value) as? String
            require(hex != null && Regex("#[0-9A-Fa-f]{6}").matches(hex)) { "Expected #RRGGBB, got $value" }
            return "Color(0xFF${hex.substring(1).uppercase()})"
        }
        fun number(value: Any?): Int = (value as? Number)?.toInt() ?: error("Expected a number, got $value")

        val json = JsonSlurper().parse(tokens.get().asFile)
        val color = json.obj("color")
        val typography = json.obj("typography")
        val text = buildString {
            appendLine("// Generated from design/coder-design-system.json by the generateDesktopSources task.")
            appendLine("// Do not edit; change the design file instead.")
            appendLine("package com.raban.etabli.probe.desktop.theme")
            appendLine()
            appendLine("import androidx.compose.ui.graphics.Color")
            appendLine("import androidx.compose.ui.unit.dp")
            appendLine("import androidx.compose.ui.unit.sp")
            appendLine()
            appendLine("internal object DesignTokens {")
            appendLine("    const val DESIGN_VERSION = \"${(json as Map<*, *>)["version"]}\"")
            for (key in listOf("accent", "accentDark", "accentLight")) {
                appendLine("    val $key = ${color(color[key])}")
            }
            for (mode in listOf("light", "dark")) {
                appendLine("    object ${mode.replaceFirstChar { it.uppercase() }} {")
                color.obj(mode).forEach { (k, v) -> appendLine("        val $k = ${color(v)}") }
                appendLine("    }")
            }
            appendLine("    object Spacing {")
            json.obj("spacing").forEach { (k, v) -> appendLine("        val $k = ${number(v)}.dp") }
            appendLine("    }")
            appendLine("    object Radius {")
            json.obj("radius").forEach { (k, v) -> appendLine("        val $k = ${number(v)}.dp") }
            appendLine("    }")
            appendLine("    object TypeScale {")
            typography.obj("scale").forEach { (k, v) -> appendLine("        val $k = ${number(v)}.sp") }
            appendLine("    }")
            appendLine("    const val FONT_MONO = \"${typography["fontMono"]}\"")
            appendLine("}")
        }
        val dir = outputDir.get().asFile.resolve("com/raban/etabli/probe/desktop/theme")
        dir.deleteRecursively()
        dir.mkdirs()
        dir.resolve("DesignTokens.kt").writeText(text)
        val info = outputDir.get().asFile.resolve("com/raban/etabli/probe/desktop/BuildInfo.kt")
        info.writeText(
            """
            |// Generated by the generateDesktopSources task. Do not edit.
            |package com.raban.etabli.probe.desktop
            |
            |internal object BuildInfo {
            |    const val VERSION = "${appVersion.get()}"
            |}
            |""".trimMargin(),
        )
    }
}

