// jpackage always appends a Debian revision ("_0.1.0-1_amd64.deb"). The suite publishes Linux
// packages as etabli-<app>_<version>_amd64.deb, so the file is renamed after packaging; the
// package metadata keeps Version 0.1.0-1.
val renameDeb by tasks.registering {
    val debDir = layout.buildDirectory.dir("compose/binaries/main/deb")
    doLast {
        debDir.get().asFile.listFiles { f -> f.name.endsWith("-1_amd64.deb") }.orEmpty().forEach { deb ->
            val target = deb.resolveSibling(deb.name.removeSuffix("-1_amd64.deb") + "_amd64.deb")
            Files.move(deb.toPath(), target.toPath(), StandardCopyOption.REPLACE_EXISTING)
            logger.lifecycle("Renamed to ${target.absolutePath}")
        }
    }
}
tasks.matching { it.name == "packageDeb" }.configureEach { finalizedBy(renameDeb) }
